/**
 * dsh-proto-lab — the two documents every run carries, written the same way by
 * every runtime.
 *
 * A run's README and NOTES are the difference between a folder of source and a
 * prototype somebody else can pick up: one says what it is and the exact command
 * that makes it go, the other says what the seed was and what to look at. Both
 * are GENERATED, which is why they can never drift from the runtime that made
 * them - and why they are written here, once, instead of in each runtime module.
 *
 * A runtime passes `{ label, slug, id, concept, seed, where }`, where `where` is
 * the runtime's own table of files and build recipe, and optionally `params` (a
 * generated run's tunables) or `paramNotes` (an example's, which are named in its
 * own source rather than generated into a shell).
 */

/**
 * The README.
 *
 * @param options - `{ label, slug, id, concept, seed, where, params, paramNotes, files }`.
 * @returns the markdown.
 */
export function readmeOf(options) {
  const lines = []
  lines.push('# ' + options.label + ' — ' + options.runtimeLabel + ' prototype')
  lines.push('')
  lines.push('> ' + options.concept)
  lines.push('')
  lines.push('Seed **' + options.seed + '** · run `' + options.id + '` · generated by `dsh-proto-lab`.')
  lines.push('')
  if (Array.isArray(options.files) && options.files.length > 0) {
    lines.push('## What is in here')
    lines.push('')
    lines.push('| file | what it is |')
    lines.push('|---|---|')
    for (const file of options.files) lines.push('| `' + file.path + '` | ' + file.what + ' |')
    lines.push('')
  }
  if (typeof options.where === 'string' && options.where !== '') {
    lines.push(options.where)
    lines.push('')
  }
  if (Array.isArray(options.params) && options.params.length > 0) {
    lines.push('## Parameters')
    lines.push('')
    lines.push('Every one of these has a control in the shell, and every one of them is read through')
    lines.push('`P(\'name\')` in the sketch — so the control and the value cannot disagree.')
    lines.push('')
    lines.push('| parameter | range | starts at |')
    lines.push('|---|---|---|')
    for (const slot of options.params) {
      lines.push('| `' + slot.name + '` | ' + slot.min + ' … ' + slot.max + ' (step ' + slot.step + ') | ' + slot.value + ' |')
    }
    lines.push('')
  }
  if (typeof options.paramNotes === 'string' && options.paramNotes !== '') {
    lines.push('## Where the numbers are')
    lines.push('')
    lines.push(options.paramNotes)
    lines.push('')
  }
  return lines.join('\n')
}

/**
 * The NOTES: one seed, one concept, one observation, three moves.
 *
 * Deliberately short. This is the file a person reads before touching anything,
 * and a long one is a file nobody reads - the algorithm is documented in the
 * source, where it can be checked against the code.
 */
export function notesOf(options) {
  const lines = []
  lines.push('# Notes — ' + options.slug)
  lines.push('')
  lines.push('- **seed**: ' + options.seed + (options.seedWhere === undefined ? '' : ' (' + options.seedWhere + ')'))
  lines.push('- **concept**: ' + options.concept)
  lines.push('- **runtime**: ' + options.runtimeLabel + (options.runtimeNote === undefined ? '' : ' — ' + options.runtimeNote))
  lines.push('')
  lines.push('## What to look at')
  lines.push('')
  for (const line of options.look ?? []) lines.push('- ' + line)
  lines.push('')
  lines.push('## What to try')
  lines.push('')
  for (const line of options.try_ ?? []) lines.push('- ' + line)
  lines.push('')
  return lines.join('\n')
}
